/**
 * refresh-gate.js — คูลดาวน์ของปุ่ม "รีเฟรชข้อมูล"
 *
 * ทำไมต้องมี:
 * การรีเฟรชหนึ่งครั้งยิง HTTP ไป Google Sheets 125 คำขอ (payload หลัก) หรือ 140 คำขอ (ชีตวัสดุ)
 * `inFlight` ใน server.js กันได้เฉพาะตอนกด **ทับซ้อนกัน** — ถ้าผู้บริหารสามคนกดไล่กันทีละคน
 * จะยิงเต็มรอบสามครั้ง = 375 คำขอในไม่กี่นาที เสี่ยงโดน Google ตอบ 429
 * ซึ่งจะทำให้ทั้ง Dashboard กลายเป็น stale พอดี
 *
 * **ทำไมเป็นคูลดาวน์ต่อเซิร์ฟเวอร์ ไม่ใช่โควตารายคน:**
 * สิ่งที่กำลังปกป้องคือโควตาฝั่ง Google ที่ทุกคนใช้ร่วมกัน ไม่ใช่ต้นทุนรายคน
 * โควตารายคนไม่คุมโหลดรวมเลย (10 คน × 5 ครั้ง/วัน = 13,250 คำขอ)
 * ส่วนคูลดาวน์ 2 นาทีคุมได้แน่นอนว่าไม่เกิน 30 รอบ/ชั่วโมงไม่ว่าจะมีผู้ใช้กี่คน
 * (ต่างจากโควตาแชทใน server.js ที่ต้นทุนเป็นเงินต่อคำถามจริง ๆ จึงเหมาะกับการนับรายคน)
 *
 * ไม่มี I/O ไม่มี global state จึงเทสต์ได้ตรง ๆ ด้วยการฉีด `now`
 */

/**
 * @param {{cooldownMs:number, now?:()=>number}} opts
 */
export function createRefreshGate({ cooldownMs, now = Date.now } = {}) {
  /** scope → เวลาที่ดึงจริงครั้งล่าสุด (ms) */
  const lastAt = new Map();

  return {
    /**
     * ขอสิทธิ์ดึงข้อมูลสด — ไม่เปลี่ยนสถานะใด ๆ เรียกซ้ำได้
     * @param {string} scope แยกตามชุดข้อมูล ('reports' / 'supplyLog') เพราะคนละจำนวนคำขอกัน
     */
    check(scope) {
      const prev = lastAt.get(scope) ?? 0;
      const waitMs = Math.max(0, prev + cooldownMs - now());
      return { allowed: waitMs === 0, waitMs, cooldownMs, lastAt: prev || null };
    },

    /**
     * จดว่าเพิ่งดึงจริงไป
     *
     * **ต้องเรียกก่อนเริ่มโหลด ไม่ใช่หลังโหลดสำเร็จ** ถ้าจดตอนสำเร็จ
     * เวลา Google ล่มคูลดาวน์จะไม่เคยเริ่มนับ แล้วทุกคนจะยิงซ้ำรัว ๆ
     * ตอนที่ปลายทางกำลังแย่ที่สุดพอดี
     */
    note(scope) {
      lastAt.set(scope, now());
    },
  };
}
